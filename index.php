            if (window.pageYOffset >= sectionTop) {
                current = section.getAttribute('id');
            }
        });

        navLinks.forEach(link => {
            link.classList.remove('text-eco-blue');
            if (link.getAttribute('href') === '#' + current) {
                link.classList.add('text-eco-blue');
            }
        });
    }, { passive: true });

})();

