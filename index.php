(function() {
    'use strict';

    // ── Preloader ───────────────────────────────────────
    const preloader = document.getElementById('preloader');

    function hidePreloader() {
        if (!preloader || preloader.classList.contains('hidden-screen')) return;
        preloader.classList.add('hidden-screen');
        document.body.style.overflow = '';
        setTimeout(() => preloader.remove(), 700);
    }

    document.body.style.overflow = 'hidden';
    window.addEventListener('load', hidePreloader);
    setTimeout(hidePreloader, 3500); // safety: never block the page if an asset stalls

    // ── Hero Video (autoplay + infinite loop, always on) ───
    const heroVideo = document.getElementById('heroVideo');
    if (heroVideo) {
        heroVideo.muted = true;
        heroVideo.defaultMuted = true;
        heroVideo.loop = true;

        const startVideo = () => {
            const attempt = heroVideo.play();
            if (attempt !== undefined) attempt.catch(() => {});
        };

        // Retry playback at every readiness stage — first frame, enough data, fully buffered
        ['loadeddata', 'canplay', 'canplaythrough'].forEach(evt => {
            heroVideo.addEventListener(evt, startVideo);
        });
        startVideo();

        // If the browser ever ignores the loop attribute, restart manually
        heroVideo.addEventListener('ended', () => {
            heroVideo.currentTime = 0;
            startVideo();
        });

        // Auto-resume after any interruption (autoplay policy, memory pressure, etc.)
        heroVideo.addEventListener('pause', () => {
            if (!heroVideo.ended) setTimeout(startVideo, 300);
        });

        // Resume when the visitor returns to the tab or window
        document.addEventListener('visibilitychange', () => {
            if (document.visibilityState === 'visible' && heroVideo.paused) startVideo();
        });
        window.addEventListener('focus', () => {
            if (heroVideo.paused) startVideo();
        });
    }

    // ── Mobile Menu Toggle ──────────────────────────────
    const menuToggle = document.getElementById('menuToggle');
    const mobileNav = document.getElementById('mobileNav');
    const menuClose = document.getElementById('menuClose');
    const mobileOverlay = document.getElementById('mobileOverlay');

    function openMenu() {
        mobileNav.classList.add('open');
        mobileOverlay.classList.remove('hidden');
        requestAnimationFrame(() => mobileOverlay.classList.remove('opacity-0'));
        document.body.style.overflow = 'hidden';
    }

    function closeMenu() {
        mobileNav.classList.remove('open');
        mobileOverlay.classList.add('opacity-0');
        setTimeout(() => mobileOverlay.classList.add('hidden'), 300);
        document.body.style.overflow = '';
    }

    menuToggle.addEventListener('click', openMenu);
    menuClose.addEventListener('click', closeMenu);
    mobileOverlay.addEventListener('click', closeMenu);

